#!/usr/bin/env python3
import argparse
from pathlib import Path
import re
import sqlite3


def identifier_bands(connection):
    bands = {
        'Fixture': (5_090_000, 5_099_999),
        'Operator': (14_000_000, 14_999_999),
        'Package Creature': (15_000_000, 15_999_999),
        'Package Gameobject': (16_000_000, 16_999_999),
        'Curated, separate key spaces': (1_000_000, 5_200_499),
    }
    rows = []
    for table in ['creature', 'gameobject']:
        guids = [row[0] for row in connection.execute(f'SELECT guid FROM {table}')]
        for band, (low, high) in bands.items():
            count = sum(low <= guid <= high for guid in guids)
            rows.append(f'| {table} | {max(guids, default=0)} | {band} | {low}..{high} | {count} |')
    return '\n'.join(rows)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    connection = sqlite3.connect(args.source.resolve().as_uri() + '?mode=ro', uri=True)
    connection.execute('PRAGMA trusted_schema=OFF')
    connection.execute('PRAGMA query_only=ON')
    templates = {row[0] for row in connection.execute('SELECT entry FROM creature_template WHERE patch <= 10')}
    spawns = list(connection.execute('SELECT id,id2,id3,id4,id5 FROM creature WHERE patch_min <= 10 AND patch_max >= 10 AND (spawn_flags & 2) = 0'))
    script = (root / 'importer/scripts/import-world.sh').read_text()
    defaults = re.search(r'INCLUDE_CREATURES-([0-9,]+)', script).group(1)
    presentation = (root / 'importer/src/eventai_presentation.rs').read_text()
    displays = re.search(r'DISPLAY_TEMPLATE_ENTRIES:.*?= &\[(.*?)\]', presentation, re.S).group(1)
    groups = {
        'INCLUDE_CREATURES defaults': [int(value) for value in defaults.split(',')],
        'Spell summon dependencies': [416, 1860, 1863, 5676, 5677, 12861],
        'Content checks and known empty services': [926,836,1681,3593,4200,328,377,906,913,917,927,295,491,589,449,476,474,644,643,642,1763,646,647,639,2485,4732,2879,15351],
        'EventAI display dependencies, behavior recheck due in S6': [int(value.replace('_','')) for value in re.findall(r'[0-9][0-9_]*', displays)],
        'Encounter Bindings, behavior recheck due in S6': [4832,*range(9034,9041),11492,4625,3914,4274,3927,8440,3671,3669,3670,3673,3654,11391],
    }
    print('# Creature identifier audit\n')
    print('Generated by `python3 importer/scripts/audit-creature-ids.py <mangos.sqlite>` at vmangos `464179081673cfd240f7ffe7f0daf96bca0b5a70`, patch 10. Counts include all enabled source positions, before profile boundaries and population selection.\n')
    print('| Use | Entry | Template exists | Enabled source positions |\n| --- | ---: | --- | ---: |')
    for group, entries in groups.items():
        for entry in entries:
            print(f'| {group} | {entry} | {entry in templates} | {sum(entry in row for row in spawns)} |')
    missing = sorted({entry for entries in groups.values() for entry in entries} - templates)
    print(f'\nMissing production template dependencies: {missing}. Summon-only templates need no placed spawn. Template existence does not verify script behavior. Rajaxx bindings remain for S6.\n')
    print('| Table | Maximum GUID | Identifier band | Bounds | Source GUIDs |\n| --- | ---: | --- | --- | ---: |')
    print(identifier_bands(connection))
    print('\nThe broad curated bounds separate Package Identifier Ranges across table key spaces. Spawn Claims check the narrower fixture band and their own encoding bounds. These counts audit identifiers; they do not test Package apply.')
    connection.close()


if __name__ == '__main__':
    main()
