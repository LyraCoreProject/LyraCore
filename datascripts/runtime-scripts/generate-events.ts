import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export interface EventField {
  readonly name: string;
  readonly type: "number" | "boolean" | "string" | "PlayerEntity";
  readonly source: string;
}

export interface EventDefinition {
  readonly event: string;
  readonly payloadType: string;
  readonly actor: string;
  readonly target: string;
  readonly binding: readonly [string, string];
  readonly typeName: string;
  readonly fields: readonly EventField[];
}

const ROOT = dirname(fileURLToPath(import.meta.url));
export const EVENTS: readonly EventDefinition[] = JSON.parse(readFileSync(join(ROOT, "events.json"), "utf8"));

function checkCatalogue(): void {
  const names = new Set<string>();
  const bindings = new Set<string>();
  const types = new Set<string>();
  for (const definition of EVENTS) {
    const binding = definition.binding.join(".");
    if (names.has(definition.event) || bindings.has(binding) || types.has(definition.typeName)) {
      throw new Error(`duplicate event, binding or type in events.json: ${definition.event}`);
    }
    names.add(definition.event);
    bindings.add(binding);
    types.add(definition.typeName);
    const fields = new Set(["name", "actor", "target"]);
    for (const field of definition.fields) {
      if (fields.has(field.name)) throw new Error(`${definition.event}: duplicate field ${field.name}`);
      fields.add(field.name);
      if (field.type === "PlayerEntity" && (field.name !== "player" || field.source !== "actor")) {
        throw new Error(`${definition.event}: a required Character Entity must come from the actor`);
      }
    }
  }
}

function groups(): Map<string, EventDefinition[]> {
  const grouped = new Map<string, EventDefinition[]>();
  for (const definition of EVENTS) {
    const group = definition.binding[0];
    const events = grouped.get(group) ?? [];
    events.push(definition);
    grouped.set(group, events);
  }
  return grouped;
}

export function typeScriptDeclarations(): string {
  const lines = [
    "// GENERATED by generate-events.ts from events.json and runtime-script.base.d.ts. DO NOT EDIT.",
    readFileSync(join(ROOT, "runtime-script.base.d.ts"), "utf8").trimEnd(),
    "",
  ];
  for (const definition of EVENTS) {
    lines.push(`interface ${definition.typeName} extends ScriptEvent {`, `  readonly name: ${JSON.stringify(definition.event)};`);
    for (const field of definition.fields) {
      lines.push(`  readonly ${field.name}: ${field.type};`);
    }
    lines.push("}", "");
  }
  lines.push("declare const events: {");
  for (const [group, definitions] of groups()) {
    lines.push(`  readonly ${group}: {`);
    for (const definition of definitions) {
      lines.push(`    ${definition.binding[1]}(this: void, handler: (this: void, event: ${definition.typeName}) => number | void, options?: EventBindingOptions): void;`);
    }
    lines.push("  };");
  }
  lines.push(
    "  readonly package: {",
    "    on(this: void, localName: string, handler: (this: void, event: PackageEvent) => number | void, options?: EventBindingOptions): void;",
    "  };",
    "};",
    "",
  );
  return lines.join("\n");
}

export function luaDeclarations(): string {
  const lines = [
    "-- GENERATED by generate-events.ts from events.json. DO NOT EDIT.",
    "---@meta",
    "",
    "---@class Entity",
    "---@field name string",
    "---@field is_player boolean",
    "---@field level number",
    "---@field health number",
    "---@field max_health number",
    "---@field map_id number",
    "---@field x number",
    "---@field y number",
    "---@field z number",
    "",
    "---@class PlayerEntity: Entity",
    "---@field is_player true",
    "",
    "---@class ScriptEvent",
    "---@field name string",
    "---@field actor? Entity",
    "---@field target? Entity",
    "",
    "---@class PackageEvent: ScriptEvent",
    "",
    "---@class EventBindingOptions",
    "---@field priority? integer",
    "---@field enabled? boolean",
    "",
    "---@type ScriptEvent",
    "event = nil",
    "",
    "---@param entity Entity",
    "---@param amount number",
    "function heal(entity, amount) end",
    "",
    "---@param player Entity",
    "---@param text string",
    "function send_chat(player, text) end",
    "",
    "---@param player Entity",
    "---@param amount number",
    "function grant_xp(player, amount) end",
    "",
  ];
  for (const definition of EVENTS) {
    lines.push(`---@class ${definition.typeName}: ScriptEvent`, `---@field name ${JSON.stringify(definition.event)}`);
    for (const field of definition.fields) lines.push(`---@field ${field.name} ${field.type}`);
    lines.push("");
  }
  lines.push("events = {}");
  for (const [group, definitions] of groups()) {
    lines.push(`events.${group} = {}`);
    for (const definition of definitions) {
      lines.push(
        "",
        `---@param handler fun(event: ${definition.typeName}): number?`,
        "---@param options? EventBindingOptions",
        `function events.${group}.${definition.binding[1]}(handler, options) end`,
      );
    }
  }
  lines.push(
    "",
    "events.package = {}",
    "---@param localName string",
    "---@param handler fun(event: PackageEvent): number?",
    "---@param options? EventBindingOptions",
    "function events.package.on(localName, handler, options) end",
    "",
  );
  return lines.join("\n");
}

export function rustEventNames(): string {
  return [
    "// GENERATED by generate-events.ts from events.json. DO NOT EDIT.",
    "/// Core hook names accepted by the Script Artifact parser.",
    "pub const HOOK_EVENT_NAMES: &[&str] = &[",
    ...EVENTS.map(definition => `    ${JSON.stringify(definition.event)},`),
    "];",
    "",
  ].join("\n");
}

checkCatalogue();

if (import.meta.main) {
  const outputs = new Map([
    ["runtime-script.d.ts", typeScriptDeclarations()],
    ["runtime-script.lua", luaDeclarations()],
    ["event-names.rs", rustEventNames()],
  ]);
  for (const [name, declarations] of outputs) {
    const path = join(ROOT, name);
    if (process.argv.includes("--check")) {
      if (readFileSync(path, "utf8") !== declarations) throw new Error(`${name} differs from events.json; run generate-events.ts`);
    } else {
      writeFileSync(path, declarations);
    }
  }
}
