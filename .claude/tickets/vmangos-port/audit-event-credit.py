#!/usr/bin/env python3

import argparse
import collections
import json
import pathlib
import re
import sqlite3

parser = argparse.ArgumentParser(description="Audit imported event requirements against SQL scripts and emitted AI.")
parser.add_argument("sqlite", type=pathlib.Path)
parser.add_argument("quest_sql", type=pathlib.Path)
parser.add_argument("reducers", type=pathlib.Path)
parser.add_argument("manifest", type=pathlib.Path)
args = parser.parse_args()

requirements = set()
for statement in args.quest_sql.read_text().split(";"):
    match = re.search(r"INSERT INTO game_quest_event_requirement .*? VALUES (.*)", statement, re.S)
    if match:
        requirements.update(int(quest) for _, quest in re.findall(r"\((\d+),(\d+)\)", match[1]))
if not requirements:
    raise SystemExit("No production event requirements found")
batches = json.loads(args.reducers.read_text())
credits = {int(quest) for _, batch in batches for quest in re.findall(r"quest-event:(\d+)", batch)}
manifest = json.loads(args.manifest.read_text())
reasons = {
    table: {script["id"]: script["reason"] for script in census["unsupported"]}
    for table, census in manifest["scripts"].items()
}
references = collections.defaultdict(list)
with sqlite3.connect(args.sqlite.resolve().as_uri() + "?mode=ro", uri=True) as source:
    source.row_factory = sqlite3.Row
    events = list(source.execute("SELECT id, creature_id, action1_script, action2_script, action3_script FROM creature_ai_events"))
    for table in ["creature_ai_scripts", *sorted(reasons)]:
        for row in source.execute(f'SELECT id, datalong FROM "{table}" WHERE command = 7 ORDER BY id'):
            quest = row["datalong"]
            if quest not in requirements:
                continue
            key = row["id"]
            if table != "creature_ai_scripts":
                reason = reasons[table].get(key, "No emitted event-credit instruction")
                references[quest].append(f"`{table}:{key}`: `{reason}`")
                continue
            roots = [event for event in events if key in [event[f"action{n}_script"] for n in range(1, 4)]]
            for root in roots:
                tag = f'event:{root["id"]}:creature:{root["creature_id"]}'
                findings = [finding["code"] for finding in manifest["findings"] if tag in finding.get("source_ids", [])]
                reason = ", ".join(findings) or "Event is not emitted from an EventAI template"
                references[quest].append(f'`creature_ai_scripts:{key}`, event `{root["id"]}`: `{reason}`')
            if not roots:
                references[quest].append(f"`creature_ai_scripts:{key}`: no event references this command list")

supported = requirements & credits
print("# Event-credit quest audit\n")
print("Generated by `audit-event-credit.py <sqlite> <production-quest.sql> <eventai-reducers.json> <eventai-manifest.json>`.\n")
print("The quest requirements and emitted instructions come from the full-world production plans. SQL command 7 references come from the read-only snapshot at `464179081673cfd240f7ffe7f0daf96bca0b5a70`. The script tables are unversioned. No source text is reproduced.\n")
print(f"Of {len(requirements)} event-credit quests, {len(supported)} have an emitted completion instruction and {len(requirements - credits)} remain unsupported. {len(requirements & references.keys())} have SQL command 7 references. No emitted instruction alone establishes a working player path.\n")
print("A missing SQL reference does not prove that vmangos lacks completion behavior. C++ scripts and other source mechanisms are outside this audit. The Module has no supported completion source for those quests.\n")
print("| Quest | Outcome | Source reference and reason |\n| ---: | --- | --- |")
for quest in sorted(requirements):
    outcome = "Instruction emitted, gameplay unverified" if quest in credits else "Unsupported"
    reason = "; ".join(dict.fromkeys(references[quest])) or "No SQL event-credit command references this quest; no supported completion source is implemented."
    print(f"| {quest} | {outcome} | {reason} |")
