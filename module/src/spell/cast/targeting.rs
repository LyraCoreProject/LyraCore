/// The reagents `spell_id` consumes per cast — `(item entry, count)` — from the imported
/// `game_spell_reagent` (multi-reagent). Empty = no reagents (a conjure/quest CreateItem, or a
/// non-recipe spell). Indexed by spell, so this is cheap on the cast path.
pub(crate) fn recipe_reagents(ctx: &ReducerContext, spell_id: u32) -> Vec<(u32, u32)> {
    ctx.db
        .game_spell_reagent()
        .by_spell()
        .filter(&spell_id)
        .map(|r| (r.item_entry, r.count))
        .collect()
}

/// The PROFESSION `(skill line, green floor, gray ceiling)` a craft recipe trains, from
/// `game_skill_ability`, or `None` if the spell has no profession skill-line ability (a conjure, or
/// a reagent-consuming BUFF like Arcane Intellect — its ability is a magic-school line, not a
/// profession). `green`/`gray` feed `skillup_chance_bp`; a degenerate/zero band there ⇒ always +1
/// (a recipe with no imported difficulty band still skills up). Called only when an E_CREATE_ITEM
/// craft resolves (rare), so the linear scan is off the hot path.
fn recipe_skill(ctx: &ReducerContext, spell_id: u32) -> Option<(u32, u32, u32)> {
    ctx.db
        .game_skill_ability()
        .iter()
        .filter(|a| a.spell_id == spell_id && crate::skill::is_profession_line(a.skill_line))
        .map(|a| (a.skill_line, a.green.max(0) as u32, a.gray.max(0) as u32))
        .next()
}

