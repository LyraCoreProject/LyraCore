// Section note (deliberately `//`, not `///`: it documents the targeting block below, not the next
// item — `select_targets` carries its own doc).
// Resolve which unit guids an effect lands on. Single-target kinds — `T_SELF` → the caster; the
// single-target enemy/ally/any kinds → the explicit target (or the caster when none was given). AREA /
// CHAIN kinds fan out to EVERY in-radius unit of the matching faction around the anchor (caster for a
// PBAoE — no explicit / self-cast; the explicit unit otherwise), faction-filtered + capped (see
// `select_targets`). `apply_effect` already loops the returned vec, so each in-radius unit takes the
// effect with no further changes.

/// Fallback splash radius (yards) for an AREA effect whose `radius_yd` is 0 — a melee-range PBAoE
/// (Thunder Clap / Arcane Explosion / Consecration all sit ~8–10yd). The importer should fill a real
/// radius from `Spell.dbc`; this keeps a 0-radius row from degenerating to a single target.
const MELEE_PBAOE_RADIUS_YD: f32 = 8.0;
/// Global cap on AREA targets (vanilla caps AoE around ~10–20). Also bounds the worst-case effect loop.
const AOE_MAX_TARGETS: usize = 20;

/// PURE in-radius + faction keep test for ONE AoE candidate (extracted so it's unit-testable without a
/// `ReducerContext`). `d2` is the squared distance from the splash anchor; `r2` the squared radius. For
/// an ENEMY AoE (`want_enemy`) keep a HOSTILE non-caster in range; for an ALLY AoE keep an in-range
/// FRIENDLY OR the caster itself (a self-PBAoE buff must land on the caster). The dead/same-map filters
/// are applied by the caller (they need the row, not just these scalars).
fn aoe_keep(
    d2: f32,
    r2: f32,
    want_enemy: bool,
    is_caster: bool,
    hostile: bool,
    friendly: bool,
) -> bool {
    if d2 > r2 {
        return false;
    }
    if want_enemy {
        !is_caster && hostile
    } else {
        is_caster || friendly
    }
}

/// Faction legality of a cast at a DISTINCT target, given what the spell's effects target
/// (`hits_enemy`/`hits_ally`) and the caster→target reaction (`friendly`/`hostile`). An enemy-targeted
/// effect may not land on a FRIENDLY unit; an ally-targeted effect may not land on a HOSTILE unit.
/// NEUTRAL (neither friendly nor hostile) passes both checks — stays attackable AND buffable. Returns
/// the violated target-class (for the error message) or `None` when the cast is legal. Pure → unit-tested.
pub(crate) fn faction_target_violation(
    hits_enemy: bool,
    hits_ally: bool,
    friendly: bool,
    hostile: bool,
) -> Option<&'static str> {
    if hits_enemy && friendly {
        return Some("enemies");
    }
    if hits_ally && hostile {
        return Some("allies");
    }
    None
}

pub(crate) fn select_targets(
    ctx: &ReducerContext,
    caster_guid: u64,
    explicit: u64,
    e: &SpellEffect,
    // The clicked GROUND point (118 phase 2). When `Some`, an AREA effect splashes from the dest
    // (Flamestrike/Blizzard's initial impact centered on the click), NOT the caster/explicit unit.
    dest: Option<(f32, f32, f32)>,
) -> Vec<u64> {
    let one = if explicit == 0 { caster_guid } else { explicit };
    match e.target {
        T_SELF => vec![caster_guid],
        T_TARGET_ENEMY | T_TARGET_ALLY | T_TARGET_ANY => vec![one],
        T_AREA_ENEMY | T_AREA_ALLY | T_CHAIN_ENEMY => {
            let entities = ctx.db.game_world_entity();
            let Some(caster) = entities.guid().find(caster_guid) else {
                return vec![one]; // missing caster row → single-target fallback
            };
            // Anchor POSITION: a ground-dest cast splashes from the clicked point (map/instance from the
            // caster); else a PBAoE (no explicit, or explicit == caster) splashes from the caster and a
            // targeted-AoE from the explicit unit. `(ax, ay, az)` is the splash center.
            let (a_map, a_inst, ax, ay, az) = if let Some((dx, dy, dz)) = dest {
                (caster.map_id, caster.instance_id, dx, dy, dz)
            } else {
                let anchor_guid = if explicit == 0 || explicit == caster_guid {
                    caster_guid
                } else {
                    explicit
                };
                let Some(anchor) = entities.guid().find(anchor_guid) else {
                    return vec![one];
                };
                (
                    anchor.map_id,
                    anchor.instance_id,
                    anchor.x,
                    anchor.y,
                    anchor.z,
                )
            };
            // 0-radius (a melee PBAoE with no imported radius) falls back to the melee splash const.
            let radius = if e.radius_yd > 0.0 {
                e.radius_yd
            } else {
                MELEE_PBAOE_RADIUS_YD
            };
            let r2 = radius * radius;
            let want_enemy = matches!(e.target, T_AREA_ENEMY | T_CHAIN_ENEMY);

            // Full-iter + squared-distance scan (the module's established spatial idiom — see
            // creatures/tick.rs aggro). Re-checks faction PER resolved target (the per-cast gate at
            // resolve_cast_at only validates the EXPLICIT target; a PBAoE bypasses it via explicit==0).
            let mut hits: Vec<u64> = entities
                .iter()
                .filter(|c| c.map_id == a_map && c.instance_id == a_inst && !c.dead)
                .filter_map(|c| {
                    let (dx, dy, dz) = (c.x - ax, c.y - ay, c.z - az);
                    let d2 = dx * dx + dy * dy + dz * dz;
                    if d2 > r2 {
                        return None; // out of radius — skip BEFORE the faction lookup (distance-first)
                    }
                    // Compute ONLY the faction side this AoE needs (one lookup, not both); the unused side
                    // is a dummy `false` — want_enemy selects which side aoe_keep actually reads.
                    let (hostile, friendly) = if want_enemy {
                        (crate::combat::is_hostile_target(ctx, &caster, &c), false)
                    } else {
                        (false, crate::combat::may_help(ctx, &caster, &c))
                    };
                    aoe_keep(d2, r2, want_enemy, c.guid == caster_guid, hostile, friendly)
                        .then_some(c.guid)
                })
                .collect();

            // ALLY: guarantee the caster is included (is_friendly(self,self) can be false on
            // missing/same-faction data, but a self-PBAoE buff must always land on the caster).
            if !want_enemy && !hits.contains(&caster_guid) {
                hits.push(caster_guid);
            }
            // CHAIN honors `chain_targets` as its cap; AREA uses the global AoE cap.
            let cap = if e.target == T_CHAIN_ENEMY && e.chain_targets > 0 {
                e.chain_targets as usize
            } else {
                AOE_MAX_TARGETS
            };
            hits.truncate(cap);
            // An AoE that hits nothing is a clean no-op (apply_effect loops an empty vec). Do NOT fall back
            // to the single explicit target: for an enemy PBAoE (explicit==0 → one==caster) that would land
            // the effect on the CASTER — self-damage on a whiffed enemy AoE.
            hits
        }
        _ => {
            // T_SCRIPTED / unknown → graceful single-target fallback (never mis-fire on a wide set).
            let _ = ctx;
            vec![one]
        }
    }
}

/// Next stack count on a REFRESH of an aura: bump by 1, capped at the header's `max_stacks` (floored at
/// 1 so a non-stacking aura — `max_stacks` 0 or 1 — pins at 1 → byte-identical to the pre-stacking
/// behavior). `current.max(1)` floors a legacy/0-stack row at 1 before incrementing, mirroring the
/// read-side `stacks.max(1)` in `sum_active_auras`. Pure → unit-tested. e.g. Sunder Armor (max_stacks 5):
/// 1→2→3→4→5→5 (caps), so the −90 armor effect compounds to −450 at full stacks. [pure]
fn next_stacks(current: u8, max_stacks: u8) -> u8 {
    (current.max(1) + 1).min(max_stacks.max(1))
}

/// Pick the `UNIT_FIELD_AURA` slot for a FRESH aura application, PER-SPELL (not per-effect). `existing` is
/// the target's current `(slot, spell_id)` pairs. If the target already carries this `spell_id` — a sibling
/// effect of the SAME multi-effect cast applied moments ago — reuse THAT slot so the buff renders as ONE
/// icon (vanilla shows one icon per spell, the effects are sub-parts). Otherwise the lowest free slot
/// WITHIN THE POLARITY'S RANGE: the 1.12 client renders slots `0..buff_slot_count` as the buff frame and
/// `buff_slot_count..slot_count` as the debuff frame (it sections by slot index, not by an aura flag), so a
/// debuff must never land below `buff_slot_count` (and vice versa) or it renders in the wrong row / can
/// starve the other polarity's slots. `None` ⇒ the polarity's slot range is full → the caller drops the
/// aura (never collide at slot 0). Pure → tested.
fn pick_aura_slot(
    existing: &[(u8, u32)],
    spell_id: u32,
    is_negative: bool,
    buff_slot_count: u8,
    slot_count: u8,
) -> Option<u8> {
    if let Some(&(slot, _)) = existing.iter().find(|(_, sp)| *sp == spell_id) {
        return Some(slot); // a sibling effect already placed this spell — share its slot (one icon)
    }
    let mut range = if is_negative {
        buff_slot_count..slot_count
    } else {
        0..buff_slot_count
    };
    range.find(|s| !existing.iter().any(|(es, _)| es == s))
}

/// Delete every aura on `target_guid` whose `spell_id` is in `spell_ids` (381) — the shared
/// collect-then-delete DISPLACEMENT sweep `aura_apply`'s two single-active-buff-class rules both reduce
/// to: a fresh SEAL displacing the other active seal (every sibling effect sharing its spell_id, not
/// just the A_SEAL-tagged one), and a same-NAME higher/lower rank displacing the other. Both call sites
/// compute `spell_ids` with a DIFFERENT predicate (A_SEAL-sibling scan vs. same-name spell resolution)
/// but converge on this identical shape (mirrored by `stacking.rs`'s group-eviction sweep, a third,
/// independent instance of the same pattern) — a future `spell_chain` import (work-item 102, the real
/// rank-chain data) swaps the RANK predicate that feeds this fn, never a second displacement mechanism.
/// A no-op for an empty set (nothing to displace) — every existing call site is baseline-safe by
/// construction, since an empty-set filter matches nothing either way.
fn displace_auras(
    ctx: &ReducerContext,
    target_guid: u64,
    spell_ids: &std::collections::HashSet<u32>,
) {
    if spell_ids.is_empty() {
        return;
    }
    let auras = ctx.db.game_aura();
    let displaced: Vec<u64> = auras
        .by_target()
        .filter(&target_guid)
        .filter(|a| spell_ids.contains(&a.spell_id))
        .map(|a| a.id)
        .collect();
    for id in displaced {
        auras.id().delete(id);
    }
}

// One argument per column of the effect row being applied as an aura.
#[allow(clippy::too_many_arguments)]
/// Place (or refresh) the aura for `effect` on `target_guid`, sourced from `caster_guid`, FREEZING the
/// typed snapshot (kind/amount/p0/p1/period) so ticks + combat reads are self-contained. Keyed by
/// `effect_id` so a multi-effect spell's distinct auras don't collide. Re-cast refreshes the timer +
/// re-freezes the magnitude + resets the next tick. The `UNIT_FIELD_AURA` slot is chosen PER-SPELL on a
/// fresh apply (`pick_aura_slot` — all of a spell's effects share one slot ⇒ one icon). The cast visual is
/// emitted ONCE by `resolve_cast_at`, not here. [entity]
pub(crate) fn aura_apply(
    ctx: &ReducerContext,
    e: &SpellEffect,
    hdr: &Spell,
    caster_guid: u64,
    target_guid: u64,
    cast_target_guid: u64,
    level: u8,
    points: i32,
) {
    let now = ctx.timestamp;
    // P_PCT_MAX_POWER (Mage Evocation): the effect's `amount` is a PERCENT of the caster's MAX power, not an
    // absolute per-tick figure. Convert it to an absolute HERE — BEFORE it is frozen onto the Aura row in
    // EITHER the refresh or the insert branch below — so the generic A_PERIODIC_ENERGIZE tick
    // (`scheduler::energized_value`) restores a real number each period. Reads the caster's `max_power`
    // (Evocation is self-cast, so caster == target). Every other effect keeps `points` verbatim: only this
    // p0_kind tag triggers the conversion (baseline-safe).
    let points = if e.p0_kind == P_PCT_MAX_POWER {
        let max_power = ctx
            .db
            .game_world_entity()
            .guid()
            .find(caster_guid)
            .map(|c| c.max_power)
            .unwrap_or(0);
        ((max_power as i64) * (points as i64) / 100) as i32
    } else {
        points
    };
    // Combo-FINISHER duration scaling (Slice and Dice): a spell carrying SPELL_ATTR_FINISHER_DURATION
    // derives this aura's lifetime from the caster's combo points BUILT ON THE ENEMY (`cast_target_guid`,
    // the cast's explicit target) — NOT this effect's resolved `target_guid` (SnD's haste is T_SELF → the
    // caster). Read the points BEFORE spending, set the duration, then spend EXACTLY ONCE (one aura effect
    // per such spell → one spend, on the correct (caster, enemy) key). Generic over the flag, never a
    // spell id. Baseline-safe: a spell without the bit uses the flat header duration (every existing aura).
    let duration_ms = if hdr.cast_flags & SPELL_ATTR_FINISHER_DURATION != 0 {
        let combo = crate::combo::combo_points(ctx, caster_guid, cast_target_guid);
        crate::combo::finisher_duration_ms(hdr.duration_ms, combo)
    } else {
        hdr.duration_ms
    };
    // CC diminishing returns (work-item 192): PLAYER targets only, `A_CONTROL(mechanic)` effects only —
    // `dr_category_for_effect` is `None` for every other kind/target (a creature, a non-CC aura), so this
    // is a complete no-op for every existing aura. Runs on EVERY `aura_apply` call (fresh insert AND a
    // same-spell refresh) — recasting the identical CC spell while the target is STILL under its previous
    // application is exactly the work item's t=16 vector (the second poly hasn't been REMOVED yet, so this
    // must scale the refresh too, not just a fresh insert). A `Refuse` bails out before anything else is
    // touched (no aura placed/refreshed, no other state written) — matches "immune".
    let now_micros = now.to_micros_since_unix_epoch();
    let dr_category =
        crate::spell::stacking::dr_category_for_effect(ctx, e.kind, e.p0_kind, e.p0, target_guid);
    let duration_ms = if let Some(category) = dr_category {
        match crate::spell::stacking::resolve_dr_for_target(ctx, target_guid, category, now_micros)
        {
            crate::spell::stacking::ApplyDecision::Refuse { reason } => {
                log::info!(
                    "DR: spell {} (category {category}) on {target_guid} refused ({reason})",
                    hdr.spell_id
                );
                return;
            }
            crate::spell::stacking::ApplyDecision::Apply {
                duration_scale_bp, ..
            } => ((duration_ms as u64) * (duration_scale_bp as u64) / 10_000) as u32,
        }
    } else {
        duration_ms
    };
    // u32::MAX is the importer's sentinel for DBC duration -1 (infinite / toggle auras such as
    // Devotion Aura, stances, etc.).  Set expires to Timestamp(i64::MAX) so the reaper's
    // `expires_at <= now` test is ALWAYS false — i64::MAX µs ≈ 292,000 years from epoch.
    // Any finite duration adds the millisecond count to `now` as before.
    let expires = if duration_ms == u32::MAX {
        Timestamp::from_micros_since_unix_epoch(i64::MAX)
    } else {
        now.checked_add(TimeDuration::from_micros((duration_ms as i64) * 1000))
            .unwrap_or(now)
    };
    // Do not advance DR yet. A later group or slot refusal means no aura was applied, and an
    // unsuccessful application must leave the target's diminishing-return state untouched.
    let next_tick_micros = if e.period_ms > 0 {
        now.to_micros_since_unix_epoch() + (e.period_ms as i64) * 1000
    } else {
        0
    };

    // Two ground mounts never stack (story 28): a mount landing on a target that already rides a
    // DIFFERENT mount runs the shared dismount first, which drops the whole previous mount spell (its
    // display effect AND its mounted-speed effect), so the replacement starts from a clean slate.
    // Scoped to a different spell on purpose — a recast of the SAME mount must fall through to the
    // ordinary refresh below, or a multi-effect mount would delete the sibling effect this same cast
    // had just refreshed.
    if e.kind == A_MOUNTED
        && crate::mount::active_mount_spell(ctx, target_guid)
            .is_some_and(|active| active != hdr.spell_id)
    {
        crate::mount::dismount(ctx, target_guid);
    }
    let auras = ctx.db.game_aura();
    // Single active seal: applying a seal removes the ENTIRE other seal buff (seals don't stack; a
    // re-cast of the SAME seal just refreshes via the `existing` lookup below). A multi-effect seal
    // (e.g. Seal of the Crusader's AP+haste+A_SEAL trio) is ONE buff in vanilla — displacing it must drop
    // every sibling effect sharing its spell_id, not just the A_SEAL-tagged row, or the displaced seal's
    // other effects (AP/haste) would linger as an orphaned buff after the swap. Generic over A_SEAL — no
    // spell id hardcoded here, but the OTHER seal's spell_id is looked up to scope the sibling sweep.
    // `displace_auras` is the shared collect-then-delete mechanism (381) — this call site's only job is
    // to name WHICH spell_ids it displaces.
    if e.kind == A_SEAL {
        let other_seal_spell_ids: std::collections::HashSet<u32> = auras
            .by_target()
            .filter(&target_guid)
            .filter(|a| a.eff_kind == A_SEAL && a.effect_id != e.id)
            .map(|a| a.spell_id)
            .collect();
        displace_auras(ctx, target_guid, &other_seal_spell_ids);
    }
    // Same-buff-RANK exclusivity: the importer keeps the shared base NAME across ranks
    // (Arcane Intellect R1/R2, Frost Armor/Ice Armor, Demon Skin, ...) but each rank is a DISTINCT
    // spell_id, so `pick_aura_slot`'s exact-spell_id dedupe doesn't catch a higher rank cast over a
    // lower one — both auras stacked and double-folded their stat/armor effects. Generalizes the
    // A_SEAL sibling-sweep above to ANY spell whose NAME matches this one's and whose spell_id differs:
    // resolve the OTHER rank's spell_id(s) sharing this name, then hand them to the SAME
    // `displace_auras` the seal sweep uses — one displacement mechanism, two predicates for "which
    // spell_ids". Name-keyed is the honest slice available today; the real rank-chain data
    // (`spell_chain`) is future work (work-item 102 tracks importing it) and will refine the PREDICATE
    // later (a same-named-but-unrelated pair would incorrectly collide under this heuristic —
    // acceptable for now, there is no such collision in the seed data) — the future `spell_chain`
    // import swaps this predicate, not a third displacement mechanism.
    // A re-cast of the SAME spell_id is excluded here (`a.spell_id != hdr.spell_id`) so a single-rank
    // recast still only refreshes in place via the `existing` lookup below — never displaces itself.
    if !hdr.name.is_empty() {
        let spells = ctx.db.game_spell();
        let other_rank_ids: std::collections::HashSet<u32> = auras
            .by_target()
            .filter(&target_guid)
            .filter(|a| a.spell_id != hdr.spell_id)
            .map(|a| a.spell_id)
            .filter(|&sp| {
                spells
                    .spell_id()
                    .find(sp)
                    .map(|s| s.name == hdr.name)
                    .unwrap_or(false)
            })
            .collect();
        displace_auras(ctx, target_guid, &other_rank_ids);
    }
    let existing = auras
        .by_target()
        .filter(&target_guid)
        .find(|a| a.effect_id == e.id);
    // An A_ABSORB aura's `amount_remaining` is its SHIELD POOL — seeded to the resolved magnitude at
    // apply (a re-cast re-fills it). Every other kind keeps `amount_remaining` at 0 (baseline-safe:
    // only the absorb path reads/writes it).
    let amount_remaining = if e.kind == A_ABSORB { points.max(0) } else { 0 };
    // CHANNEL freeze (A_PERIODIC_TRIGGER): the aura is a T_SELF self-channel, so `target_guid` is the CASTER;
    // the per-tick missile must fly at the cast's EXPLICIT enemy target — freeze it in `channel_target`. The
    // per-tick TRIGGER spell id (the missile, e.g. 7268) rides in `eff_p1` so the tick re-casts it without an
    // effect re-join. Every other kind keeps `channel_target` 0 and its own `e.p1` (baseline-safe — only the
    // channel kind reads these). [entity]
    let channel_target = if e.kind == A_PERIODIC_TRIGGER {
        cast_target_guid
    } else {
        0
    };
    // A_PROC_TRIGGER freezes its trigger spell the SAME way A_PERIODIC_TRIGGER does — off
    // `e.trigger_spell`, not `e.p1` (which stays free for the unrelated linked-debuff overload below). It is
    // NOT a channel, so `channel_target` above is correctly left at 0 for it.
    let eff_p1 = if e.kind == A_PERIODIC_TRIGGER || e.kind == A_PROC_TRIGGER {
        e.trigger_spell as i32
    } else {
        e.p1
    };
    // The frozen PROC PROFILE: a Proc aura carries its own event mask, chance, rate, filter, charge
    // count and cooldown length, folded here from the spell header and the `spell_proc_event` overlay,
    // so the proc pass reads one row and never re-joins either. Every non-proc kind freezes zeros,
    // which the decision reads as "never procs". A REFRESH re-freezes the whole profile and refills
    // charges to full (recasting Lightning Shield mid-fight) and deliberately leaves
    // `proc_ready_micros` alone — a running internal cooldown is not reset by a recast.
    let proc = crate::spell::proc::freeze_profile(ctx, e.kind, hdr);
    if let Some(mut a) = existing {
        // Refresh: re-freeze the magnitude + reset the cadence; keep the slot. STACKING — a re-cast of a
        // stacking aura (`max_stacks >= 2`) bumps `stacks` (capped at the header's `max_stacks`) so the
        // combat folds (which read `amount × stacks`) compound; a non-stacking aura (`max_stacks` 0/1)
        // pins `stacks` at 1, byte-identical to today. An A_ABSORB refresh re-fills the pool.
        a.stacks = next_stacks(a.stacks, hdr.max_stacks);
        a.expires_at = expires;
        a.amount = points;
        a.amount_remaining = amount_remaining;
        a.next_tick_micros = next_tick_micros;
        a.applied_at = now;
        // Re-freeze the channel snapshot on a re-cast (re-channel at a possibly-new target). Inert for
        // every non-channel aura (channel_target 0; eff_p1 == e.p1, i.e. a no-op write).
        a.eff_p1 = eff_p1;
        a.channel_target = channel_target;
        a.proc_flags = proc.flags;
        a.proc_chance = proc.chance;
        a.proc_ppm = proc.ppm;
        a.proc_ex = proc.proc_ex;
        a.proc_school_mask = proc.school_mask;
        a.proc_family_name = proc.family_name;
        a.proc_family_flags = proc.family_flags;
        a.proc_charges = proc.charges;
        a.proc_icd_ms = proc.icd_ms;
        auras.id().update(a);
    } else {
        // Stacking-group conflict (work-item 192): resolve BEFORE picking a slot, so a Refuse never
        // consumes a slot and an Apply's evictions free slots for this fresh insert. A same-spell recast
        // never reaches this branch (caught by the `existing`-by-effect_id match above) — matches "same-
        // spell-same-caster refresh keeps the existing precedence rule, runs BEFORE group logic". No-op
        // (returns `true` immediately) for the overwhelming majority of spells (not in any
        // `game_spell_group`).
        if !crate::spell::stacking::apply_group_conflict(
            ctx,
            hdr.spell_id,
            caster_guid,
            target_guid,
            crate::spell::stacking::rank_of(ctx, hdr.spell_id),
            points.saturating_abs(),
        ) {
            return; // refused — no aura placed, nothing evicted
        }
        // Pick the UNIT_FIELD_AURA slot PER-SPELL (see `pick_aura_slot`): a multi-effect aura spell shares
        // ONE slot across its effects → ONE buff icon, instead of one icon per effect.
        let existing: Vec<(u8, u32)> = auras
            .by_target()
            .filter(&target_guid)
            .map(|a| (a.slot, a.spell_id))
            .collect();
        let Some(slot) = pick_aura_slot(
            &existing,
            hdr.spell_id,
            hdr.is_negative,
            tracer_spell::BUFF_SLOT_COUNT,
            tracer_spell::AURA_SLOTS,
        ) else {
            // All slots full → DROP rather than colliding at slot 0 (which would corrupt the buff display).
            // LOUD (work-item 192): this used to be a silent drop — now it ALSO relays SMSG_SPELL_FAILURE
            // to the CASTER via the existing generic is_interrupted signal row (the same mechanism
            // `interrupt_cast` uses; `gateway/src/stdb/subscriptions.rs`'s `on_cast` relay is untouched —
            // it already fires for ANY `is_interrupted` row, keyed off `caster_guid == self_guid`, so this
            // is a module-only change with zero gateway edits) — the 17th debuff / 33rd buff is refused
            // with a clear cast-bar failure instead of vanishing silently.
            log::info!(
                "aura slot overflow: all {} slots on {target_guid} full — dropping spell {} (loud: relayed to caster {caster_guid})",
                tracer_spell::AURA_SLOTS,
                hdr.spell_id
            );
            ctx.db.game_spell_cast_event().insert(SpellCastEvent {
                // aura-slot overflow is an interrupt signal, not a pushback (delay_ms stays 0).
                is_interrupted: true,
                ..SpellCastEvent::signal(ctx, caster_guid, hdr.spell_id)
            });
            return;
        };
        auras.insert(Aura {
            id: 0,
            target_guid,
            caster_guid,
            spell_id: hdr.spell_id,
            slot,
            level,
            flags: tracer_spell::AURA_FLAGS,
            applied_at: now,
            expires_at: expires,
            effect_id: e.id,
            eff_kind: e.kind,
            amount: points,
            eff_p0: e.p0,
            eff_p0_kind: e.p0_kind,
            eff_p1,
            period_ms: e.period_ms,
            amount_remaining,
            stacks: 1,
            next_tick_micros,
            channel_target,
            enters_combat: e.enters_combat, // freeze so the periodic-energize tick re-enters combat (Bloodrage)
            proc_flags: proc.flags,
            proc_chance: proc.chance,
            proc_ppm: proc.ppm,
            proc_ex: proc.proc_ex,
            proc_school_mask: proc.school_mask,
            proc_family_name: proc.family_name,
            proc_family_flags: proc.family_flags,
            proc_charges: proc.charges,
            proc_icd_ms: proc.icd_ms,
            proc_ready_micros: 0, // a fresh Proc is ready at once
        });
    }

    // Both branches above have now successfully refreshed or inserted an aura. Only at this
    // point may the target's DR progression advance; group/slot refusals returned earlier.
    if let Some(category) = dr_category {
        crate::spell::stacking::bump_dr_level(
            ctx,
            target_guid,
            category,
            now_micros,
            expires.to_micros_since_unix_epoch(),
        );
    }

    // Re-derive max-health (STA) / max-mana (INT) AFTER the aura row is placed, but ONLY when THIS aura
    // is an A_MOD_STAT(STA/INT/ALL) — so a +STA buff (Mark of the Wild's stamina effect) raises max HP on
    // apply (and a re-cast keeps it consistent). `stat_bonus` reads the now-present aura row, so the
    // recompute sees this aura's contribution. Any other aura kind skips this (no work → baseline-safe).
    if aura_moves_vitals(e.kind, e.p0) {
        recompute_vitals(ctx, target_guid);
    }
    // #517: re-derive the character-sheet numbers the SAME way — gated on `aura_moves_sheet` (a wider
    // gate than vitals: STR/AGI/SPI stat auras and Battle-Shout-style AP auras move the sheet but not a
    // pool). AFTER the vitals recompute so a STA/INT aura's `recompute_sheet` sees the already-updated
    // `e.spirit` field.
    if crate::spell::aura_moves_sheet(e.kind, e.p0) {
        recompute_sheet(ctx, target_guid);
    }
    // Same shape again for the land-mount projection: with the `A_MOUNTED` row now placed, re-derive
    // `mount_display_id` from the aura set so the frozen display reaches the client. Gated on
    // `mount_aura_moves_mount`, so every non-mount aura skips it entirely.
    if crate::mount::mount_aura_moves_mount(e.kind, e.p0) {
        crate::mount::recompute_mount(ctx, target_guid);
    }

    // Combo-FINISHER spend (Slice and Dice): SPEND the combo points AFTER the duration read above
    // (read-then-spend, same call, same (caster, enemy) key). SnD has exactly ONE aura effect (the haste),
    // so this fires the spend EXACTLY ONCE per cast — and `spend_combo` deletes nothing on a 0-combo cast,
    // so a no-combo SnD is a harmless base-duration self-buff. Gated on the flag → no-op for every other
    // aura (no spend code runs). Keyed on `cast_target_guid` (the enemy), never `target_guid` (the caster).
    if hdr.cast_flags & SPELL_ATTR_FINISHER_DURATION != 0 {
        crate::combo::spend_combo(ctx, caster_guid, cast_target_guid);
    }

    // DEBUFF-APPLICATION THREAT (266/276): landing a hostile aura on a CREATURE adds flat,
    // caster-level-scaled threat — the vanilla mechanic that makes Sunder Armor a threat BUILDER
    // (its armor debuff deals no damage, and threat here was damage-only, so a warrior tank had
    // nothing but white swings between taunt pins). Uniform over `is_negative`: a debuff that
    // ALSO damages gets this small flat term on top of its damage threat, matching vanilla's
    // apply+tick threat shape. PLAYER casters only (a creature debuffing a player writes no
    // threat table; creature-on-creature stays untouched).
    if hdr.is_negative {
        let entities = ctx.db.game_world_entity();
        let caster_is_player = entities
            .guid()
            .find(caster_guid)
            .map(|c| c.is_player())
            .unwrap_or(false);
        let target_is_creature = entities
            .guid()
            .find(target_guid)
            .map(|t| !t.is_player())
            .unwrap_or(false);
        if caster_is_player && target_is_creature {
            crate::threat::add_threat(ctx, target_guid, caster_guid, (level as i64) * 5);
        }
    }
}

/// Apply the LINKED debuff `linked_spell_id` on `target_guid` — the generic "aura X also applies debuff Y"
/// mechanic (Weakened Soul). Loads the linked spell's header + its aura effect(s) and places each via
/// the SAME `aura_apply` a normal cast uses (so it freezes/refreshes/stacks/reaper-expires identically to
/// any other aura — no parallel bookkeeping). `caster_guid`/`level` are threaded through so the debuff's
/// `caster_guid`/`level` columns are correct (Weakened Soul is "caused by" the shielding priest); its own
/// magnitude is computed the same `effect_amount` way as a normal cast, using the CASTER's level (matching
/// every other aura-apply path). `cast_target_guid` is `target_guid` itself — a linked debuff has no
/// separate enemy-key concept (SPELL_ATTR_FINISHER_DURATION callers pass a distinct value; a linked debuff
/// never carries that bit). Graceful no-op if the linked spell or its effect rows are missing (a
/// data-authoring gap, not a crash) — the PRIMARY aura (already applied by the caller) is unaffected either
/// way. Non-aura effects on the linked spell (there are none in the Weakened Soul data) would just apply
/// their own instant behavior; only aura effects reach `aura_apply` here, mirroring `apply_effect`'s own
/// dispatch. [entity]
pub(crate) fn apply_linked_debuff(
    ctx: &ReducerContext,
    linked_spell_id: u32,
    caster_guid: u64,
    target_guid: u64,
    level: u8,
) {
    let Some(linked_hdr) = ctx.db.game_spell().spell_id().find(linked_spell_id) else {
        log::info!("linked debuff {linked_spell_id} has no game_spell header — skipped");
        return;
    };
    for e in ctx
        .db
        .game_spell_effect()
        .by_spell()
        .filter(&linked_spell_id)
        .filter(|e| e.kind & KIND_AURA_BIT != 0)
    {
        let points = effect_amount(
            e.base_points,
            e.die_sides,
            e.per_level,
            level as u32,
            linked_hdr.spell_level,
            linked_hdr.max_level,
            ctx.random::<u32>(),
        );
        aura_apply(
            ctx,
            &e,
            &linked_hdr,
            caster_guid,
            target_guid,
            target_guid,
            level,
            points,
        );
    }
}

// One argument per column of the effect row being applied.
#[allow(clippy::too_many_arguments)]
/// Dispatch ONE effect onto ONE target. Aura kinds (high bit) route to `aura_apply`; instant kinds to
/// their handler. The 7 ported behaviors are wired; every other kind is a graceful no-op + log (so an
/// unmapped import LOADS and casts as a safe no-op instead of mis-firing). [entity]
/// Apply ONE spell effect to `target_guid`. Returns an `EffectHit` breaking down the post-mitigation
/// DAMAGE this effect dealt + the crit flag / resisted / absorbed amounts (the
/// E_DAMAGE/E_WEAPON_STRIKE/E_JUDGEMENT/E_FINISHER_DAMAGE arms surface `apply_target_damage`'s figures);
/// every non-damaging arm (auras, heals, energize, …) returns `EffectHit::none()`. The caller sums these
/// onto the cast-GO row so the gateway can relay the floating damage number (SMSG_SPELLNONMELEEDAMAGELOG)
/// with the crit/resist/absorb breakdown.
pub(crate) fn apply_effect(
    ctx: &ReducerContext,
    e: &SpellEffect,
    hdr: &Spell,
    caster_guid: u64,
    target_guid: u64,
    cast_target_guid: u64,
    level: u8,
    points: i32,
    // The clicked GROUND point (118 phase 2) — only the E_PERSISTENT_AREA arm reads it (anchors the patch
    // at the dest); every other effect ignores it. `None` for all non-ground casts.
    dest: Option<(f32, f32, f32)>,
    // This effect is running inside a **Triggered Cast** (a fired Proc). Every hit it deals is marked
    // Triggered, so it grants nothing and raises no proc event — the structural reason a proc can
    // never start a proc.
    triggered: bool,
) -> EffectHit {
    // The hit a damage arm below hands to the shared pipeline: this spell, and the proc event its
    // source raises — or Triggered, raising nothing, when the whole cast was one.
    let hit_of = |source: crate::combat::HitSource, crit: bool| {
        crate::combat::Hit::spell(
            if triggered {
                crate::combat::HitSource::Triggered
            } else {
                source
            },
            hdr.spell_id,
            crit,
        )
    };
    if e.kind & KIND_AURA_BIT != 0 {
        // CC IMMUNITY: an `A_CONTROL` crowd-control effect (a stun/root/…) is REFUSED if the target is
        // immune to that mechanic (an active `A_IMMUNITY(mechanic)` aura). The effect simply doesn't land
        // — no aura is placed — so the unit is never stunned/rooted while the immunity holds. Gated per
        // EFFECT (not per cast), so a multi-effect spell still applies its non-CC effects. Baseline-safe:
        // `is_immune_to_mechanic` is `false` for any unit without an `A_IMMUNITY` aura → unchanged.
        if e.kind == A_CONTROL
            && e.p0_kind == P_MECHANIC
            && is_immune_to_mechanic(ctx, target_guid, e.p0)
        {
            log::info!(
                "spell {} A_CONTROL(mechanic {}) refused — target {target_guid} is immune",
                e.spell_id,
                e.p0
            );
            return EffectHit::none(); // a refused CC aura deals no damage
        }
        // All aura kinds are PLACED identically (the difference is how tick_auras / combat READ the
        // frozen row). A_PERIODIC_DAMAGE/HEAL (ticked), A_MOD_COMBAT (combat-read), A_FLAG (passive
        // marker) are wired; an aura kind with no tick/read handler is simply an inert marker for now.
        aura_apply(
            ctx,
            e,
            hdr,
            caster_guid,
            target_guid,
            cast_target_guid,
            level,
            points,
        );
        // Linked-debuff APPLY (Weakened Soul, #013): the twin of the refusal gate in `resolve_cast_at` — a
        // nonzero `e.p1` names a SEPARATE spell to also apply on `target_guid` right after this aura lands
        // (PW:Shield's absorb effect names Weakened Soul). Generic over the kind/spell id: any aura effect
        // can opt in via its `p1`, the engine never names one. No-op if the linked spell/effect isn't loaded
        // (data-missing → graceful skip, never panics) or `p1 == 0` (every existing aura effect).
        if e.p1 != 0 {
            apply_linked_debuff(ctx, e.p1 as u32, caster_guid, target_guid, level);
        }
        // CC interrupt: an action-blocking control (stun/poly/fear — NOT root, which still allows
        // casting) landing on a unit that is MID-CAST cancels its in-progress cast AND any channel it is
        // running (Arcane Missiles stops if you're stunned/feared). Checked AFTER the aura lands so
        // `is_action_blocked` sees it. Routes through `break_channel` (which both interrupts the timed cast
        // and deletes the channel aura) so CC tears down a channel for free — without it the deferred cast
        // would still fire if the CC expired before the cast finished, and a channel would keep ticking
        // (the tick arm's own action-blocked check would END it next tick, but breaking it now is prompt).
        // No-op when the new aura isn't action-blocking, or the target has no cast/channel. [entity]
        if e.kind == A_CONTROL && is_action_blocked(ctx, target_guid) {
            break_channel(ctx, target_guid);
        }
        return EffectHit::none(); // an aura effect deals no direct cast damage
    }
    match e.kind {
        E_DUEL => {
            if e.p0_kind == P_GAMEOBJECT_ENTRY {
                crate::duel::request_duel(ctx, caster_guid, target_guid, e.p0.max(0) as u32);
            }
            EffectHit::none()
        }
        E_DAMAGE => {
            // Binary spell MISS: a level-derived chance the spell fully misses (4% vs equal, up to
            // 17% vs +3) — a clean 0-damage outcome with NO threat/scaling. Rolled BEFORE everything else,
            // so a miss short-circuits before any scaling/threat work. Target level looked up; absent →
            // assume equal level.
            let target_level = ctx
                .db
                .game_world_entity()
                .guid()
                .find(target_guid)
                .map(|t| t.level)
                .unwrap_or(level as u32);
            if (ctx.random::<u32>() % 10_000) < spell_miss_chance_bp(level as u32, target_level) {
                return EffectHit::none();
            }
            // Spell-power scaling: final = base_points + spell_power·coeff. The caster's spell power
            // (INT ramp + COMBAT_SPELL_POWER auras) is 0 for a low-INT, un-buffed caster → `scaled ==
            // points` (the existing Fireball still hits for 20 on the L2 player — baseline byte-identical).
            let sp = spell_power(ctx, caster_guid, hdr.school_mask);
            let scaled = compose_magnitude(points, sp, SPELL_POWER_COEFF_PCT);
            // Spell-modifier fold (264): the caster's A_SPELLMOD damage-op auras (fire-damage-%
            // talents etc.) move THIS spell's direct damage — flat then percent, before crit
            // (crit amplifies the modified base, mirroring the cast-time fold's lockstep rule).
            let (dmg_flat, dmg_pct) =
                crate::spell::math::spell_mod(ctx, caster_guid, SPELLMOD_OP_DAMAGE, hdr);
            let scaled =
                crate::spell::math::apply_spell_mod(scaled.max(0) as u32, dmg_flat, dmg_pct) as i32;
            // Spell crit: roll the caster's spell-crit chance (SPELL_CRIT_BP + COMBAT_CRIT auras); a crit
            // deals ×1.5 (vanilla spell crit, NOT ×2 like melee), applied to the spell-power-scaled base
            // BEFORE resistance/absorb (crit amplifies, mitigation then shaves). The pipeline is
            // scale → CRIT → resist → absorb → health → threat.
            let is_crit = (ctx.random::<u32>() % 10_000) < spell_crit_bp(ctx, caster_guid);
            let crit_scaled = apply_spell_crit(scaled, is_crit);
            // Magic resistance: the target's resistance to the spell's school reduces the (crit-scaled)
            // damage, vanilla-style, capped 75%. No matching resist aura → unchanged (baseline-safe).
            // `apply_target_damage` folds absorb shields in AFTER this, so threat accrues on the final
            // post-ABSORB damage actually dealt, not on this pre-absorb resisted value.
            let after_resist =
                apply_resistance(ctx, target_guid, caster_guid, hdr.school_mask, crit_scaled);
            // resisted = what the school resist shaved off the crit-scaled hit (clamp ≥0 — a partial resist
            // floors at 1, never goes negative).
            let resisted = crit_scaled.saturating_sub(after_resist).max(0) as u32;

            // PROJECTILE IMPACT DELAY: a genuine ranged bolt (range_yd > 0, a DISTINCT target on the
            // caster's map) defers the health write + damage log until the missile's travel time elapses —
            // vanilla lands Shadow Bolt on IMPACT, not the instant the cast resolves. The crit/resist roll
            // above still happens AT CAST TIME (matching vanilla); only the health write + damage-log signal
            // are deferred. `SMSG_SPELL_GO` (the trajectory) still fires synchronously at cast resolution —
            // untouched — so the missile visually flies while the damage is pending. A self-cast / adjacent
            // target (range_yd == 0, e.g. Frost Armor's self buff) or a missing/cross-map target takes the
            // INSTANT path unchanged.
            if hdr.range_yd > 0 && target_guid != caster_guid {
                if let (Some(caster), Some(target)) = (
                    ctx.db.game_world_entity().guid().find(caster_guid),
                    ctx.db.game_world_entity().guid().find(target_guid),
                ) {
                    if caster.map_id == target.map_id && caster.instance_id == target.instance_id {
                        let dist =
                            distance_3d(caster.x, caster.y, caster.z, target.x, target.y, target.z);
                        let travel_ms = projectile_travel_ms(dist, PROJECTILE_SPEED_YPS);
                        if travel_ms > 0 {
                            let fire_at = ctx
                                .timestamp
                                .checked_add(TimeDuration::from_micros((travel_ms as i64) * 1000))
                                .unwrap_or(ctx.timestamp);
                            ctx.db
                                .game_pending_spell_impact()
                                .insert(PendingSpellImpact {
                                    scheduled_id: 0,
                                    scheduled_at: ScheduleAt::Time(fire_at),
                                    caster_guid,
                                    target_guid,
                                    spell_id: hdr.spell_id,
                                    school_index: if hdr.school_mask == 0 {
                                        0u8
                                    } else {
                                        hdr.school_mask.trailing_zeros() as u8
                                    },
                                    is_crit,
                                    resisted,
                                    after_resist,
                                    triggered,
                                });
                            // The impact (and its damage log) lands later via `fire_spell_impact` — this
                            // cast's own GO/damage-log row carries no damage (no double-count/double-log).
                            return EffectHit::none();
                        }
                    }
                }
            }
            let (dealt, absorbed) = apply_target_damage(
                ctx,
                target_guid,
                caster_guid,
                after_resist,
                hit_of(crate::combat::HitSource::Spell, is_crit),
            );
            EffectHit {
                dealt,
                resisted,
                absorbed,
                crit: is_crit,
                healed: 0,
            }
        }
        E_WEAPON_STRIKE => {
            // A PHYSICAL melee ability (Mortal Strike et al.): damage = the caster's weapon swing roll +
            // this effect's flat bonus (`points`), with a melee crit + armor mitigation, computed by
            // `combat::weapon_strike_damage` (reuses the swing-range/crit/armor math). Physical → no magic
            // resistance (armor already shaved inside the helper). `apply_target_damage` folds absorb +
            // threat + the kill, exactly like E_DAMAGE. No-op if either unit left the world.
            let entities = ctx.db.game_world_entity();
            if let (Some(caster), Some(target)) = (
                entities.guid().find(caster_guid),
                entities.guid().find(target_guid),
            ) {
                let (dmg, crit) =
                    crate::combat::weapon_strike_damage(ctx, &caster, &target, points);
                // Physical strike: no magic resist; the melee crit is already folded into the damage
                // inside weapon_strike_damage, and rides the `Hit` so a crit-only Proc (Flurry) can
                // read it. Surface dealt+absorbed; the EffectHit's `crit`/`resisted` stay 0 (the
                // cast-row `is_crit` means specifically "the E_DAMAGE magic-crit roll landed").
                let (dealt, absorbed) = apply_target_damage(
                    ctx,
                    target_guid,
                    caster_guid,
                    dmg as i32,
                    hit_of(crate::combat::HitSource::MeleeSpell, crit),
                );
                EffectHit::dmg(dealt, absorbed)
            } else {
                EffectHit::none()
            }
        }
        E_HEAL => EffectHit::heal(apply_heal(ctx, hdr, caster_guid, target_guid, points)),
        E_HEAL_MAX_HEALTH => {
            // Lay on Hands: heal the target to FULL max health regardless of `points` (the DBC
            // HealMaxHealth effect carries base ~0 — it means "fill to max", not "heal N"). Set health to
            // max and credit the effective restored amount as heal-threat (overheal — already-full — adds 0,
            // exactly like apply_heal). Generic over the kind, never a spell id; spell-power-agnostic (a
            // max-heal has nothing to scale).
            if let Some(mut t) = ctx.db.game_world_entity().guid().find(target_guid) {
                let before = t.health;
                t.health = t.max_health;
                let effective = t.health.saturating_sub(before);
                ctx.db.game_world_entity().guid().update(t);
                crate::threat::add_heal_threat(ctx, caster_guid, target_guid, effective);
            }
            EffectHit::none()
        }
        E_DISPEL => {
            // The dispelled CATEGORY: the effect's `p0` (the authored override) if set, else the
            // dispelling spell's header `dispel_type`. 0 = strip every foreign aura (the baseline —
            // Dispel Magic 527 has p0=0 + dispel_type=0, so it strips everything).
            let category = if e.p0 != 0 {
                e.p0 as u8
            } else {
                hdr.dispel_type
            };
            let removed = dispel_target(ctx, target_guid, category);
            log::info!("dispel (cat {category}) on {target_guid} removed {removed} debuff(s)");
            EffectHit::none()
        }
        E_ENERGIZE => {
            if let Some(mut t) = ctx.db.game_world_entity().guid().find(target_guid) {
                t.power = energized_value(t.power, t.max_power, points);
                ctx.db.game_world_entity().guid().update(t);
            }
            // An energize effect flagged `enters_combat` (Bloodrage) puts the caster in combat so the
            // granted resource isn't immediately out-of-combat-decayed — data-driven, no spell id.
            if e.enters_combat {
                crate::combat::enter_combat(ctx, caster_guid);
            }
            EffectHit::none()
        }
        E_TAUNT => {
            // Taunt: top the caster's threat on the target CREATURE so the retarget pass switches it to
            // the caster (the threat-yank). Only meaningful on a creature target — a no-op against a
            // player (players choose their own target; they carry no threat table). `points` is unused.
            if ctx
                .db
                .game_world_entity()
                .guid()
                .find(target_guid)
                .map(|t| !t.is_player())
                .unwrap_or(false)
            {
                crate::threat::taunt(ctx, target_guid, caster_guid);
            }
            EffectHit::none()
        }
        E_CREATE_ITEM => {
            // Conjure / quest item: create `points` of item `e.p0` (a game_item_template entry) in the
            // CASTER's inventory — vanilla CreateItem always gives to the caster, not the explicit target.
            // Reuses the shared `items::grant_item` (free backpack slot, one stack). A failure (inventory
            // full, or the item template not loaded — the importer P4 dependency) is logged, NOT
            // propagated: the cast still completes (graceful, like the other handlers). `points` is the
            // DBC count (already +1-adjusted at import), floored at 1.
            let entry = e.p0.max(0) as u32;
            let count = points.max(1) as u32;
            if entry == 0 {
                log::info!(
                    "spell {} E_CREATE_ITEM with no item entry (p0=0) — skipped",
                    e.spell_id
                );
            } else if let Err(err) = crate::items::grant_item(ctx, caster_guid, entry, count) {
                log::info!(
                    "spell {} E_CREATE_ITEM: could not grant {count}x item {entry} to {caster_guid}: {err}",
                    e.spell_id
                );
                // CRAFT (282): the reagents were already consumed (the gate in resolve_cast_at), so a
                // failed product grant (full bag) must NOT eat them — refund EVERY reagent (vanilla refunds
                // an unstorable craft). A conjure/quest CreateItem has no reagents → this loop is empty.
                for (item, cnt) in recipe_reagents(ctx, e.spell_id) {
                    let _ = crate::items::grant_item(ctx, caster_guid, item, cnt);
                }
            } else if let Some((line, green, gray)) = recipe_skill(ctx, e.spell_id) {
                // CRAFT skill-up (282) — the profession-loop's third leg, co-located with the product grant.
                // Reaching here means the craft fully succeeded → climb the recipe's OWN profession line one
                // step toward its cap, with the REAL difficulty band (green floor .. gray ceiling) from
                // game_skill_ability. A no-op if the line isn't learned or is at cap; a degenerate/zero band
                // ⇒ always +1 (skillup_chance_bp). Non-craft E_CREATE_ITEM (conjure) has no profession
                // ability → None → skipped.
                crate::skill::gain_profession_skill(ctx, caster_guid, line, green, gray);
            }
            EffectHit::none()
        }
        E_TRIGGER => {
            // Cast the linked spell NOW at the SAME target, routed through the shared cast core so the
            // triggered spell runs its OWN effect list (a proc / "cast X which casts Y" chain). Guards:
            // `trigger_spell == 0` is no-op (unset link); a spell triggering ITSELF (`trigger_spell ==
            // e.spell_id`) is skipped to avoid unbounded recursion. The trigger reuses the caster +
            // level; its own GCD/cost/range gates apply — a rejected trigger is logged, never panics.
            // The triggered spell routes through its OWN resolve_cast_at, which emits its OWN cast-GO event
            // (with its OWN damage log) — so its damage is NOT folded into this parent cast's row (no
            // double-count / double-log). Return 0 here.
            if e.trigger_spell != 0 && e.trigger_spell != e.spell_id {
                if let Err(err) = resolve_cast_at(
                    ctx,
                    caster_guid,
                    e.trigger_spell,
                    level,
                    target_guid,
                    false,
                    false,
                    None,
                ) {
                    log::info!(
                        "spell {} triggered {} which did not resolve: {}",
                        e.spell_id,
                        e.trigger_spell,
                        err
                    );
                }
            }
            EffectHit::none()
        }
        E_CHARGE => {
            charge_to_target(ctx, caster_guid, target_guid);
            EffectHit::none()
        }
        E_BLINK => {
            // Distance is DATA-DRIVEN: the effect's DBC radius (SpellRadius.dbc via the importer's
            // `radius_yd`) — Blink carries 20yd. Fall back to BLINK_YD only for unauthored (0) data.
            blink_forward(ctx, caster_guid, e.radius_yd);
            EffectHit::none()
        }
        E_RECALL_HOME => {
            // Hearthstone (#387): recall the caster to its bound home, always into instance 0 (the open
            // world) even from inside a dungeon — `recall_to_home` resolves the durable char row's
            // home_map/x/y/z itself, so no target/effect params are read here.
            crate::world::recall_to_home(ctx, caster_guid);
            EffectHit::none()
        }
        E_DISMOUNT => {
            // Dazed's mount-removal half: run the shared land-dismount on the resolved target. An
            // instant effect like any other, so an unlanded cast (resisted, immune, no target) never
            // reaches here and the target stays mounted (story 27). Silent no-op on an unmounted
            // target, and idempotent if two dismount sources land on the same tick.
            crate::mount::dismount(ctx, target_guid);
            EffectHit::none()
        }
        E_PERSISTENT_AREA => {
            // GROUND-AoE (118): spawn a fixed-position damage area at the resolved target's position
            // (T_SELF/target-0 → the caster; a future clicked-ground variant anchors at the dest coords).
            // `tick_ground_areas` re-scans + damages from here on; this cast effect just STAMPS the row.
            // `points` is the per-tick magnitude. resolve_cast_at already rejected a 0-radius area.
            // `dest` Some → the patch anchors at the clicked ground point; None → the resolved entity
            // (Consecration's T_SELF paladin).
            create_ground_area(ctx, e, hdr, caster_guid, target_guid, points, dest);
            EffectHit::none()
        }
        E_CONVERT_RESOURCE => {
            convert_health_to_power(ctx, caster_guid, points);
            EffectHit::none()
        }
        E_POWER_BURN => {
            // MANA-only gate: the vanilla effect reads the target's power type and returns a
            // silent no-op on anything else (rage/energy) — the cast still resolves, it just does
            // nothing on this target. Read straight off `unit_bytes_0` byte 3, same as `is_rage_user`.
            let Some(mut t) = ctx.db.game_world_entity().guid().find(target_guid) else {
                return EffectHit::none();
            };
            if ((t.unit_bytes_0 >> 24) & 0xFF) as u8 != lyracore_shared::packing::power_type::MANA {
                return EffectHit::none();
            }
            let drained = mana_burn_drain(t.power, points);
            if drained == 0 {
                return EffectHit::none();
            }
            t.power -= drained;
            ctx.db.game_world_entity().guid().update(t);
            let damage = mana_burn_damage(drained, e.p1);
            let (dealt, absorbed) = apply_target_damage(
                ctx,
                target_guid,
                caster_guid,
                damage as i32,
                hit_of(crate::combat::HitSource::Spell, false),
            );
            EffectHit::dmg(dealt, absorbed)
        }
        E_JUDGEMENT => {
            // Unleash the caster's active SEAL: a one-time holy hit on the target derived from the seal
            // value, then consume the seal. Generic — reads the A_SEAL aura, never a spell id. No seal →
            // no-op. (Damage = the seal coefficient; the exact vanilla Judgement-of-Righteousness formula
            // is a tuning refinement.)
            let seal = seal_amount(ctx, caster_guid);
            if seal > 0 {
                let (dealt, absorbed) = apply_target_damage(
                    ctx,
                    target_guid,
                    caster_guid,
                    seal,
                    hit_of(crate::combat::HitSource::Spell, false),
                );
                remove_seal_auras(ctx, caster_guid);
                EffectHit::dmg(dealt, absorbed)
            } else {
                EffectHit::none()
            }
        }
        E_ADD_COMBO => {
            // Rogue GENERATOR: +1 combo point on the target (capped at 5); the finisher reads it. Generic
            // over game_combo_point, never a spell id.
            crate::combo::add_combo_point(ctx, caster_guid, target_guid);
            EffectHit::none()
        }
        E_FINISHER_DAMAGE => {
            // Rogue FINISHER: damage scales with the combo points built on this target (base_points is the
            // PER-POINT damage), then spend them. Generic — reads game_combo_point, never a spell id.
            let combo = crate::combo::combo_points(ctx, caster_guid, target_guid);
            let dmg = crate::combo::finisher_damage(points, combo);
            let hit = if dmg > 0 {
                let (dealt, absorbed) = apply_target_damage(
                    ctx,
                    target_guid,
                    caster_guid,
                    dmg,
                    hit_of(crate::combat::HitSource::MeleeSpell, false),
                );
                EffectHit::dmg(dealt, absorbed)
            } else {
                EffectHit::none()
            };
            crate::combo::spend_combo(ctx, caster_guid, target_guid);
            hit
        }
        E_RESURRECT => {
            // Offer a revive to a DEAD ally: emit SMSG_RESURRECT_REQUEST and wait for the target's
            // CMSG_RESURRECT_RESPONSE accept — vanilla never revives a player without their consent.
            // No-op on a living target (nothing to offer) and on a non-player target (creatures have no
            // client to prompt; a future "always accept" NPC-rez path is out of scope). The actual revive
            // (restore `points`% of max hp/power + clear the death/ghost state, mirroring corpse.rs
            // `reclaim_corpse`) lives in `resurrect_response`, gated on accept.
            if let Some(t) = ctx.db.game_world_entity().guid().find(target_guid) {
                if t.dead && t.is_player() {
                    let caster_name = ctx
                        .db
                        .game_character()
                        .guid()
                        .find(caster_guid)
                        .map(|c| c.name)
                        .unwrap_or_default();
                    ctx.db
                        .game_resurrect_request()
                        .target_guid()
                        .delete(target_guid);
                    ctx.db.game_resurrect_request().insert(ResurrectRequest {
                        target_guid,
                        target_identity: t.owner_identity,
                        caster_guid,
                        caster_name,
                        points,
                        created_at: ctx.timestamp,
                    });
                }
            }
            EffectHit::none()
        }
        E_PICKPOCKET => {
            // Grant the rogue copper from the CREATURE target WITHOUT engaging (no combat, no aggro, no
            // melee row — distinct from kill loot). ONCE PER SPAWN: a creature already pickpocketed this
            // life is rejected (the `pickpocketed` marker), so the same spawn can't be drained twice. Money
            // is the creature's TEMPLATE range (`money_min`/`money_max` — the SAME source the kill path
            // uses, reused via `roll_money`), falling back to the level heuristic for un-imported creatures
            // (`money_max == 0`). NOT rank-scaled (vanilla pickpocket isn't). Item rows (work-item 210):
            // `roll_pickpocket_loot` rolls the creature's `game_pickpocket_loot` table into
            // `game_corpse_loot` keyed on the TARGET's (still-alive) guid, inside this SAME once-gate, so
            // items can never be drained twice per life either. Never on players (no pockets / not a
            // creature). [entity]
            let entities = ctx.db.game_world_entity();
            if let Some(mut target) = entities.guid().find(target_guid) {
                if !target.is_player() && !target.dead && !target.pickpocketed {
                    let copper = ctx
                        .db
                        .game_creature_template()
                        .entry()
                        .find(target.entry)
                        .filter(|t| t.money_max > 0)
                        .map(|t| crate::combat::roll_money(ctx, t.money_min, t.money_max))
                        .unwrap_or_else(|| pickpocket_copper(target.level));
                    if let Some(mut rogue) = entities.guid().find(caster_guid) {
                        rogue.money = rogue.money.saturating_add(copper);
                        entities.guid().update(rogue);
                    }
                    // Mark picked BEFORE rolling: roll_pickpocket_loot's refresh_lootable does its
                    // own fetch+write of this row (LOOTABLE flag), and writing our pre-roll snapshot
                    // AFTERWARDS clobbered that flag — the rolled items were unreachable (review catch).
                    let target_entry = target.entry;
                    target.pickpocketed = true; // a re-pickpocket this life is rejected
                    entities.guid().update(target);
                    crate::loot::roll_pickpocket_loot(ctx, target_entry, target_guid);
                }
            }
            EffectHit::none()
        }
        E_INTERRUPT => {
            // Kick: cancel the TARGET's in-progress (timed) cast — delete its game_pending_cast row(s) so
            // the spell never resolves — AND lock the interrupted cast's SCHOOL (the Kick silence:
            // `interrupt_cast_and_lock` writes a game_school_lockout row the cast gate reads). Generic over
            // the kind, never a spell id; the importer reclassifies the raw vanilla InterruptCast effect
            // (68) to E_INTERRUPT. Safe no-op if the target isn't mid-cast (nothing to cancel/lock). Uses
            // the lock wrapper (not the bare `interrupt_cast`) so ONLY a Kick locks the school — a CC that
            // happens to interrupt a cast (stun/poly/fear) stays a pure cancel. The lockout window comes
            // from `game_spell.duration_ms` (the SPELL HEADER row, NOT `game_spell_effect` — SpellEffect
            // has no duration_ms column). Vanilla values: Kick = 5000 ms, Counterspell = 8000 ms,
            // Pummel = 4000 ms. To change a lockout window, edit `game_spell.duration_ms` on the header
            // row; there is no effect-level duration field. Falls back to 5 s when the header carries 0.
            let lockout_ms = if hdr.duration_ms > 0 {
                hdr.duration_ms as i64
            } else {
                5_000
            };
            interrupt_cast_and_lock(ctx, target_guid, lockout_ms);
            EffectHit::none()
        }
        E_REDUCE_THREAT => {
            // Feint: a one-time drop of the CASTER's CURRENT threat by the effect MAGNITUDE on EVERY
            // creature it is a source on (floored at 0) — the rogue slides down each mob's aggro list and
            // the retarget pass re-points them at the new top source (the tank). The vanilla data encodes
            // Feint's threat drop as a NEGATIVE Threat-effect base (e.g. −150), so the reduction amount is
            // `|points|` — `reduce_threat_from_source` then SUBTRACTS that positive magnitude. DISTINCT
            // from Fade (an A_MOD_COMBAT(COMBAT_THREAT) percent on FUTURE threat). The effect is
            // self-sourced — `target_guid` is ignored (the importer forces it T_SELF, so
            // `target_guid == caster_guid` here anyway). Generic over the kind, never a spell id.
            crate::threat::reduce_threat_from_source(ctx, caster_guid, (points as i64).abs());
            EffectHit::none()
        }
        E_NEXT_SWING => {
            // On-next-swing QUEUE (Heroic Strike / Cleave): instead of hitting NOW, queue this spell onto the
            // CASTER's next melee swing. Set `next_swing_spell`; the swing path (combat::resolve_swing) reads
            // the queued spell's E_NEXT_SWING base_points as bonus damage on a LANDED swing and clears the
            // field. The rage is VALIDATED at press but CHARGED at the swing-fire (resolve_swing, 114) —
            // vanilla defers the deduction; a fizzle (rage dropped below cost before the swing) un-queues
            // without firing. A missed swing still charges + spends the queue (vanilla). Generic over the kind, never a spell id;
            // the importer reclassifies Heroic Strike/Cleave's weapon-damage E_DAMAGE to E_NEXT_SWING by name.
            // No-op if the caster left the world.
            if let Some(mut c) = ctx.db.game_world_entity().guid().find(caster_guid) {
                c.next_swing_spell = e.spell_id;
                ctx.db.game_world_entity().guid().update(c);
            }
            EffectHit::none()
        }
        E_SUMMON_PET => {
            // Summon a persistent PET creature owned by the caster (Summon Imp → an Imp). The summoned
            // creature's entry is the effect's p0 (p0_kind = P_ENTRY, a game_creature_template entry —
            // mirroring how E_CREATE_ITEM puts the item entry in p0). The handler despawns any existing pet
            // first (one pet per owner — a re-summon replaces it), then spawns the new pet at the caster
            // with owner_guid = caster. Generic over the kind — the importer maps the raw vanilla Summon
            // effect (56) to E_SUMMON_PET with the misc_value (the creature entry) → p0; the engine never
            // names Summon Imp. The pet then rides the behavior cycle's pet phase (follow/engage) +
            // the existing chase/melee. Melee Imp for v1 (Firebolt is a follow-up via a creature rotation
            // row). No-op if p0 is 0 or the creature template isn't loaded (logged inside).
            let entry = e.p0.max(0) as u32;
            crate::creatures::summon_pet(ctx, caster_guid, entry);
            EffectHit::none()
        }
        E_TAME_CREATURE => {
            if let Err(error) = crate::creatures::tame_creature(ctx, caster_guid, target_guid) {
                log::info!("tame completion for caster {caster_guid} and target {target_guid} failed: {error}");
            }
            EffectHit::none()
        }
        E_SET_STANCE => {
            // Switch the caster's stance/form to the effect's p0 (the taxonomy STANCE_* 0-based id —
            // Warrior Battle/Defensive/Berserker 0/1/2, Druid Bear/Cat/DireBear 3/4/5 since 156).
            // Writing the field IS the switch — the old stance is overwritten (a single mutually-exclusive
            // scalar), so there is NO aura bookkeeping: the Defensive mitigation/threat are FOLDS keyed on
            // this field (taxonomy STANCE_DEFENSIVE_*), so the instant the field changes the prior stance's
            // contribution vanishes for free. Generic over the kind — the importer reclassifies the
            // stance/form spells' inert ModShapeshift marker to E_SET_STANCE BY NAME and packs the 0-based
            // stance id into p0; the engine never names a spell id. p0 is bounded to a valid u8 stance.
            // No-op if the caster left the world.
            let new_stance = e.p0.clamp(0, u8::MAX as i32) as u8;
            if let Some(mut c) = ctx.db.game_world_entity().guid().find(caster_guid) {
                if c.stance != new_stance {
                    // Vanilla 1.12 clears RAGE on a stance switch (the "stance dance" cost; Tactical Mastery
                    // later retains some — not in this slice). Guarded to the RAGE power type, derived from
                    // class (DATA, not a hardcode) — so a future caster/energy stance isn't wrongly drained.
                    // Mana AND energy are spared by design; vanilla has no discrete "lose rage" effect, this
                    // wipe is engine behavior keyed on power type. Extracted to a pure predicate so the
                    // switch-vs-power-type gate is unit-testable without a live ReducerContext.
                    let power_type = lyracore_shared::packing::power_type::for_class(c.class());
                    let clears_power = stance_switch_clears_power(c.stance, new_stance, power_type);
                    c.stance = new_stance;
                    if clears_power {
                        c.power = 0;
                    }
                    // Pack shapeshift form into UNIT_FIELD_BYTES_1[2] so the 5875 client swaps its
                    // action bar / model: the vanilla form id via `client_form_for_stance` (Battle=17,
                    // Defensive=18, Berserker=19 — byte-identical to the old inline `stance + 17` —
                    // plus Bear=5, Cat=1, DireBear=8). Byte 3 (the ghost vis flag) is preserved unchanged.
                    let form_id = client_form_for_stance(new_stance) << 16;
                    c.unit_bytes_1 = (c.unit_bytes_1 & 0xFF00_0000) | form_id;
                    ctx.db.game_world_entity().guid().update(c);
                } else if form_recast_toggles_off(c.stance, new_stance) {
                    // Recasting the ACTIVE druid form leaves it — back to caster form: stance 0 + a
                    // ZERO form byte, the same value a druid spawns with (see the predicate's doc for
                    // the warrior/druid asymmetry and the client_form_for_stance(0) trap). No power
                    // wipe: not a stance-to-stance switch (bear rage is a documented 156 limitation).
                    c.stance = 0;
                    c.unit_bytes_1 &= 0xFF00_0000;
                    ctx.db.game_world_entity().guid().update(c);
                }
            }
            EffectHit::none()
        }
        other => {
            // Unmapped / E_SCRIPTED residue: a graceful no-op + log (the import safety net — casts and
            // does nothing, vs doing the wrong thing). Spells that LOOK scripted in the raw DBC but are
            // really a known effect (Holy Light → a heal, Life Tap → a resource convert, Charge → a rush)
            // are reclassified to a generic kind at IMPORT time (the importer's curated correction), so
            // they arrive here as E_HEAL / E_CONVERT_RESOURCE / E_CHARGE and never reach this arm.
            log::info!(
                "spell {} effect kind 0x{other:02x} not implemented (graceful no-op)",
                e.spell_id
            );
            EffectHit::none()
        }
    }
}

// --- Generic handlers for the kinds reclassified at import. No spell ids here: the importer's curated
// correction maps the raw-DBC quirks (Holy Light's script-heal, Life Tap's drain, Charge's effect 22)
// onto generic kinds (E_HEAL / E_CONVERT_RESOURCE / E_CHARGE); the engine stays version-agnostic. ---

/// Apply a heal of `points` (spell-power-scaled) to `target_guid` and credit heal-threat. The E_HEAL arm
/// (Holy Light reclassifies to E_HEAL at import, so it routes here too) — one heal formula, not two.
fn apply_heal(
    ctx: &ReducerContext,
    hdr: &Spell,
    caster_guid: u64,
    target_guid: u64,
    points: i32,
) -> u32 {
    let sp = spell_power(ctx, caster_guid, hdr.school_mask);
    let scaled = compose_magnitude(points, sp, SPELL_POWER_COEFF_PCT);
    if let Some(mut t) = ctx.db.game_world_entity().guid().find(target_guid) {
        let before = t.health;
        t.health = healed_value(t.health, t.max_health, scaled);
        let effective = t.health.saturating_sub(before); // overheal generates no threat (vanilla)
        ctx.db.game_world_entity().guid().update(t);
        crate::threat::add_heal_threat(ctx, caster_guid, target_guid, effective);
        effective
    } else {
        0
    }
}

/// E_CONVERT_RESOURCE handler: drain `amount` of the CASTER's health and add the same to its power 1:1
/// (Life Tap), never lethal (clamp the drain to leave >=1 HP — vanilla won't kill you). `energized_value`
/// clamps to max_power. (Generalizes to arbitrary from/to pools via params later.)
fn convert_health_to_power(ctx: &ReducerContext, caster_guid: u64, amount: i32) {
    let amount = amount.max(0) as u32;
    if let Some(mut c) = ctx.db.game_world_entity().guid().find(caster_guid) {
        let drain = amount.min(c.health.saturating_sub(1));
        c.health -= drain;
        c.power = energized_value(c.power, c.max_power, drain as i32);
        ctx.db.game_world_entity().guid().update(c);
    }
}

/// E_POWER_BURN drain math (117, Mana Burn): floor-at-available — never drains more than the target
/// actually has, and never fails/refuses the cast on a low/empty pool (vanilla drains
/// `min(available, requested)`). Pure, unit-tested.
fn mana_burn_drain(power: u32, points: i32) -> u32 {
    (points.max(0) as u32).min(power)
}

/// E_POWER_BURN damage math (117): `drained * ratio_bp / 100`, integer floor (vanilla damage =
/// drained mana * EffectMultipleValue; Mana Burn's is 0.5, carried on the effect row as `p1` = 50
/// basis-points). `ratio_bp <= 0` (unauthored/default data) is treated as 100 (1:1) so a spell that
/// never got its multiplier seeded doesn't silently deal zero damage. Pure, unit-tested.
fn mana_burn_damage(drained: u32, ratio_bp: i32) -> u32 {
    let ratio_bp = if ratio_bp <= 0 { 100 } else { ratio_bp as u32 };
    (drained as u64 * ratio_bp as u64 / 100) as u32
}

/// Where a charge ENDS: `stop_yd` short of the target on the target->caster line (so the caster lands
/// facing in). Already inside `stop_yd` -> stay put. Pure (unit-tested).
fn charge_stop(cx: f32, cy: f32, tx: f32, ty: f32, stop_yd: f32) -> (f32, f32) {
    let (dx, dy) = (cx - tx, cy - ty);
    let dist = (dx * dx + dy * dy).sqrt();
    if dist <= stop_yd {
        (cx, cy)
    } else {
        (tx + dx / dist * stop_yd, ty + dy / dist * stop_yd)
    }
}

/// Where Blink LANDS: `yd` forward of `(x, y)` along `orientation`. Pure (unit-tested).
fn blink_dest(x: f32, y: f32, orientation: f32, yd: f32) -> (f32, f32) {
    (x + orientation.cos() * yd, y + orientation.sin() * yd)
}

/// Blink lands this far short of the collision ray's first-hit point (issue #523) — a small
/// clearance so the mage's own collision radius doesn't clip back into the geometry it just
/// stopped at (the wall/column/cart PLANE, not "the last whole nav cell before it" — that was the
/// grid-clamp's coarser guarantee).
const BLINK_CLEARANCE_YD: f32 = 1.0;

/// Blink: teleport the caster `dist_yd` FORWARD along its facing (Mage Blink). Self-cast — no target.
/// Reuses the teleport core exactly like Charge, but toward a fixed forward point rather than a unit.
/// `dist_yd` is the effect's DBC radius (data-driven, 20yd for Blink) — `resolve_cast_at` already
/// rejected the cast if it was 0, so no fallback here (a silent default would hide mis-seeded data).
///
/// Collision (#523, decision #10 §10): when exact vmap data is consuming
/// (`vmap::vmap_enabled`), clamp on the COLLISION ray's first-hit point (WMO + M2 doodads —
/// `vmap::collision_ray`, not the WMO-only LoS ray `has_los` uses) minus `BLINK_CLEARANCE_YD`, so
/// Blink lands right at the obstacle's true plane instead of the nearest whole nav cell before it
/// — carts and abbey columns stop Blink exactly at the collision surface. A wall inside the
/// clearance margin (point-blank) → stay put rather than teleport into geometry. Falls back to the
/// pre-523 grid step-back loop (`nav::has_los`, 2yd steps) when vmap is off — the same rollback
/// posture `nav::has_los` itself keeps.
pub(crate) fn blink_forward(ctx: &ReducerContext, caster_guid: u64, dist_yd: f32) {
    let entities = ctx.db.game_world_entity();
    let Some(caster) = entities.guid().find(caster_guid) else {
        return;
    };
    if crate::vmap::vmap_enabled(ctx, caster.map_id) {
        let (fx, fy) = blink_dest(caster.x, caster.y, caster.orientation, dist_yd);
        let a = [caster.x, caster.y, caster.z];
        let b = [fx, fy, caster.z];
        let (nx, ny) = match crate::vmap::collision_ray(ctx, caster.map_id, a, b) {
            Some(hit) => {
                let (dx, dy) = (hit[0] - caster.x, hit[1] - caster.y);
                let hit_dist = (dx * dx + dy * dy).sqrt();
                let land_dist = hit_dist - BLINK_CLEARANCE_YD;
                if land_dist <= 0.0 {
                    return; // wall inside the clearance margin — stay put
                }
                (
                    caster.x + dx / hit_dist * land_dist,
                    caster.y + dy / hit_dist * land_dist,
                )
            }
            None => (fx, fy), // clear ray (or no vmap data this cell) — the full distance
        };
        crate::world::teleport_player(
            ctx,
            caster_guid,
            caster.map_id,
            0,
            nx,
            ny,
            caster.z,
            caster.orientation,
        );
        return;
    }
    let mut yd = dist_yd;
    while yd > 0.0 {
        let (nx, ny) = blink_dest(caster.x, caster.y, caster.orientation, yd);
        if crate::nav::has_los(
            ctx,
            caster.map_id,
            (caster.x, caster.y, caster.z),
            (nx, ny, caster.z),
        ) {
            crate::world::teleport_player(
                ctx,
                caster_guid,
                caster.map_id,
                0,
                nx,
                ny,
                caster.z,
                caster.orientation,
            );
            return;
        }
        yd -= 2.0;
    }
}

/// GROUND-AoE (118): stamp a `game_ground_area` row at `anchor_guid`'s position (T_SELF/target-0 → the
/// caster; the clicked-ground dest once plumbed). The area lives for the spell's `duration_ms` and its
/// own `tick_ground_areas` re-scans + damages. `amount` is the per-tick magnitude, `e.radius_yd` the
/// zone radius (resolve_cast_at already rejected 0). One area per cast (Consecration is T_SELF → the
/// select_targets loop calls this once). No-op if the anchor entity is gone or the duration is infinite.
fn create_ground_area(
    ctx: &ReducerContext,
    e: &SpellEffect,
    hdr: &Spell,
    caster_guid: u64,
    anchor_guid: u64,
    amount: i32,
    // The clicked GROUND point (118 phase 2). `Some` → the area anchors there (map/instance still come from
    // the caster); `None` → it anchors on `anchor_guid`'s entity position (Consecration's T_SELF paladin).
    dest: Option<(f32, f32, f32)>,
) {
    let entities = ctx.db.game_world_entity();
    // With a ground dest, map/instance come from the CASTER (the click carries no map); position is the
    // dest. Without one, the whole anchor is the resolved entity's row (self/target).
    let (map_id, instance_id, x, y, z) = match dest {
        Some((dx, dy, dz)) => {
            let Some(caster) = entities.guid().find(caster_guid) else {
                return;
            };
            (caster.map_id, caster.instance_id, dx, dy, dz)
        }
        None => {
            let Some(anchor) = entities.guid().find(anchor_guid) else {
                return;
            };
            (
                anchor.map_id,
                anchor.instance_id,
                anchor.x,
                anchor.y,
                anchor.z,
            )
        }
    };
    let now = ctx.timestamp;
    // A 0 / u32::MAX (infinite) duration has no place as a ground patch — ground AoEs are always timed.
    if hdr.duration_ms == 0 || hdr.duration_ms == u32::MAX {
        return;
    }
    let Some(expires_at) =
        now.checked_add(TimeDuration::from_micros((hdr.duration_ms as i64) * 1000))
    else {
        return;
    };
    let period_ms = if e.period_ms > 0 { e.period_ms } else { 1000 };
    // Perf catalog 1.20: the 500ms ground tick is demand-armed — it disarms itself once the area
    // table drains, so re-arm it here, at the one place an area is born.
    crate::spell::scheduler::arm_ground_area_tick(ctx);
    let area = ctx.db.game_ground_area().insert(GroundArea {
        id: 0,
        spell_id: e.spell_id,
        caster_guid,
        map_id,
        instance_id,
        x,
        y,
        z,
        radius_yd: e.radius_yd,
        amount: amount.max(0),
        school_mask: hdr.school_mask,
        period_ms,
        // First tick one period after the cast (mirrors a DoT's first tick landing after amplitude).
        next_tick_micros: now.to_micros_since_unix_epoch() + (period_ms as i64) * 1000,
        expires_at,
    });
    // The client-visible swirl (118): one DYNAMICOBJECT per area — the 5875 client renders the
    // ground effect from its DYNAMICOBJECT_SPELLID SpellVisual (a CREATE relayed by the gateway).
    // Guid = HIGHGUID_DYNAMICOBJECT | the area's fresh id; the tick's reap deletes it in lockstep.
    ctx.db
        .game_dynamic_object()
        .insert(crate::spell::DynamicObject {
            guid: dynamic_object_guid(area.id),
            caster_guid,
            spell_id: e.spell_id,
            map_id,
            instance_id,
            x,
            y,
            z,
            radius_yd: e.radius_yd,
        });
}

/// The wire guid for a ground area's DynamicObject: vanilla HIGHGUID_DYNAMICOBJECT (0xF100) in the
/// top 16 bits over the `game_ground_area` id — same `(HIGH << 48) | low` scheme as corpses (0xF101)
/// and gameobjects (0xF110), so the spaces never collide.
pub(crate) fn dynamic_object_guid(area_id: u64) -> u64 {
    (0xF100u64 << 48) | area_id
}

/// Charge (261): RUSH the caster along the ground into melee of the target — a server-driven spline (the
/// same `SMSG_MONSTER_MOVE` leg creatures use for chase), NOT the old instant teleport-snap. Lands ~3yd
/// short facing the target. The straight rush is obstruction-clamped (vanilla Charge stops short on
/// blocked terrain — it does NOT path-find around, so no A*). The +rage rides a separate E_ENERGIZE
/// effect and the arrival ROOT is a follow-up; this is purely the movement half.
///
/// `agent_safe:false`: whether the 5875 client accepts a server spline for its OWN unit without a
/// desync/teleport-cheat flag needs a live eye. Server-verifiable half = the landing is walkable-clamped
/// and inside melee range, which is what `debug_*` + SQL assert.
fn charge_to_target(ctx: &ReducerContext, caster_guid: u64, target_guid: u64) {
    let entities = ctx.db.game_world_entity();
    let (Some(caster), Some(target)) = (
        entities.guid().find(caster_guid),
        entities.guid().find(target_guid),
    ) else {
        return;
    };
    let (sx, sy) = charge_stop(caster.x, caster.y, target.x, target.y, 3.0);
    let (nx, ny) = charge_clamp(ctx, caster.map_id, caster.x, caster.y, sx, sy);
    let facing = (target.y - caster.y).atan2(target.x - caster.x); // always face the target
    let (ddx, ddy) = (nx - caster.x, ny - caster.y);
    let dist = (ddx * ddx + ddy * ddy).sqrt();
    if dist < 0.5 {
        // Nowhere to rush (on top of the target, or walled in at the feet): just face in, no spline.
        if let Some(mut c) = entities.guid().find(caster_guid) {
            c.orientation = facing;
            entities.guid().update(c);
        }
        return;
    }
    let nz = crate::terrain::snap_z(ctx, caster.map_id, nx, ny, target.z);
    let duration_ms = ((dist / lyracore_shared::constants::speeds::CHARGE) * 1000.0) as u32;
    let now_ms = (ctx.timestamp.to_micros_since_unix_epoch() / 1000) as u32;
    // Emit the rush leg for the PLAYER guid — the gateway relay (build_monster_move) is type-agnostic,
    // so a player mover_guid rides the same SMSG_MONSTER_MOVE path as a creature chase leg.
    // ONE relay path (perf 2.3): the rush leg rides the spline row, which the gateway's
    // `build_monster_move` relay reads — it is type-agnostic, so a PLAYER mover_guid is fine. This
    // site still wrote `game_creature_move_event` after that table lost its subscriber, so Charge
    // teleported the caster server-side and never animated on any client.
    crate::creatures::tick::emit_move_spline(
        ctx,
        caster_guid,
        (caster.x, caster.y, caster.z),
        (nx, ny, nz),
        duration_ms,
        true,
        now_ms,
        caster.map_id,
        caster.instance_id,
        (caster.grid_x, caster.grid_y),
    );
    // Advance authoritative position to the landing NOW (the spline only animates the client toward it)
    // so the follow-up swing/melee reads the correct spot — exactly the chase-pass contract.
    if let Some(mut c) = entities.guid().find(caster_guid) {
        let (gx, gy) = lyracore_shared::spatial::grid_cell(nx, ny);
        c.x = nx;
        c.y = ny;
        c.z = nz;
        c.grid_x = gx;
        c.grid_y = gy;
        c.cell = lyracore_shared::spatial::grid_cell_id(gx, gy);
        c.orientation = facing;
        c.last_move_ms = now_ms;
        entities.guid().update(c);
    }
}

/// March the straight caster->stop segment (~1yd samples) and return the last WALKABLE point before any
/// obstruction — vanilla Charge stops short on a blocked path rather than routing around it. `walkable`
/// == None (all-clear cell / off the nav slice) counts as clear, and nav-off short-circuits to the stop,
/// so this is a straight-line no-op wherever nav doesn't apply.
fn charge_clamp(
    ctx: &ReducerContext,
    map_id: u32,
    cx: f32,
    cy: f32,
    sx: f32,
    sy: f32,
) -> (f32, f32) {
    if !crate::nav::nav_enabled(ctx) {
        return (sx, sy);
    }
    let (dx, dy) = (sx - cx, sy - cy);
    let dist = (dx * dx + dy * dy).sqrt();
    if dist < 1.0 {
        return (sx, sy);
    }
    let steps = dist.ceil() as i32; // ~1 yd per sample
    let (mut lx, mut ly) = (cx, cy);
    for i in 1..=steps {
        let t = i as f32 / steps as f32;
        let (px, py) = (cx + dx * t, cy + dy * t);
        if crate::nav::walkable(ctx, map_id, px, py) == Some(false) {
            return (lx, ly); // obstruction — clamp at the last walkable sample
        }
        (lx, ly) = (px, py);
    }
    (sx, sy)
}

/// E_RESURRECT amount: `pct`% of `max`, floored at 1 (a revive must leave the unit alive). Pure
/// (unit-tested). Clamps pct to 1..=100. Power reuses the same %% inline (no floor needed there).
/// `pub(crate)` so `resurrect_response` (scheduler.rs) can apply the SAME formula at accept-time.
pub(crate) fn revive_amount(max: u32, pct: i32) -> u32 {
    let pct = pct.clamp(1, 100) as u32;
    (max.saturating_mul(pct) / 100).max(1)
}

/// E_PICKPOCKET copper: a small level-scaled pocket. Deliberate simplification: flat heuristic, a
/// real pickpocket loot table is the upgrade. Pure (unit-tested).
fn pickpocket_copper(level: u32) -> u32 {
    level.saturating_mul(13).max(1)
}

