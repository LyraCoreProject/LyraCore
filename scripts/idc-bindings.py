#!/usr/bin/env python3
"""Regenerates module/src/remote_bindings/peer, the outbox bindings of the Module's own `idc_` reducers.

Every Shard runs the same Module, so a Shard calls a Peer Shard through bindings generated from its
own Wasm. Only the `idc_` reducers go in, and they take plain arguments, so no generated types can
collide with the Module's own.

Usage: scripts/idc-bindings.py <lyracore_module.wasm> [--check]
Runs `spacetime` from PATH (or $SPACETIME) and the spacetimedb-standalone installed beside it.
"""
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / 'module/src/remote_bindings'
HEADER = '// Generated by scripts/idc-bindings.py from the Module\'s `idc_` reducers. Do not edit.\n'


def generate(wasm):
    spacetime = shutil.which(os.environ.get('SPACETIME', 'spacetime'))
    if spacetime is None:
        sys.exit('spacetime CLI not found')
    standalone = Path(os.path.realpath(spacetime)).with_name('spacetimedb-standalone')
    definition = json.loads(subprocess.run([standalone, 'extract-schema', wasm, '--host-type', 'wasm'],
        check=True, capture_output=True, text=True).stdout)
    sections = []
    for section in definition['V10']['sections']:
        [(kind, value)] = section.items()
        if kind == 'Reducers':
            sections.append({kind: [r for r in value if r['source_name'].startswith('idc_')]})
        elif kind in ('CaseConversionPolicy', 'Typespace', 'Types'):
            sections.append(section)
    with tempfile.TemporaryDirectory() as work:
        work = Path(work)
        (work / 'spacetimedb').mkdir()
        (work / 'definition.json').write_text(json.dumps({'V10': {'sections': sections}}))
        subprocess.run([spacetime, 'generate', '--no-config', '--bindings', 'module', '--lang', 'rust',
            '--module-def', 'definition.json', '--out-dir', 'out', '-y'], cwd=work, check=True, capture_output=True)
        files = sorted(path.name for path in (work / 'out').iterdir())
        if files != ['lib.rs']:
            sys.exit(f'idc_ reducers must take plain arguments; generated {files}')
        code = (work / 'out/lib.rs').read_text()
    formatted = subprocess.run(['rustfmt', '--edition', '2021', '--emit', 'stdout'], input=code,
        check=True, capture_output=True, text=True).stdout
    return {'mod.rs': HEADER + '\npub mod peer;\n', 'peer/mod.rs': HEADER + formatted}


def main():
    if len(sys.argv) not in (2, 3) or sys.argv[2:] not in ([], ['--check']):
        sys.exit(__doc__)
    files = generate(sys.argv[1])
    if sys.argv[2:] == ['--check']:
        stale = [name for name, code in files.items()
            if not (TARGET / name).is_file() or (TARGET / name).read_text() != code]
        if stale:
            sys.exit(f'module/src/remote_bindings is stale ({", ".join(stale)}); run scripts/idc-bindings.py')
        return
    for name, code in files.items():
        (TARGET / name).parent.mkdir(parents=True, exist_ok=True)
        (TARGET / name).write_text(code)


if __name__ == '__main__':
    main()
